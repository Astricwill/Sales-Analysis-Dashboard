DROP DATABASE IF EXISTS brightmart;
CREATE DATABASE brightmart;
USE brightmart;

CREATE TABLE departments (
  department_id INT PRIMARY KEY,
  department_name VARCHAR(50) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE employees (
  employee_id INT PRIMARY KEY,
  first_name VARCHAR(50),
  last_name VARCHAR(50),
  department_id INT,
  job_title VARCHAR(80),
  hire_date DATE,
  salary INT,
  manager_id INT,
  region VARCHAR(50),
  FOREIGN KEY (department_id) REFERENCES departments(department_id)
) ENGINE=InnoDB;

CREATE TABLE customers (
  customer_id INT PRIMARY KEY,
  customer_name VARCHAR(100),
  segment VARCHAR(20),
  city VARCHAR(50),
  signup_date DATE
) ENGINE=InnoDB;

CREATE TABLE products (
  product_id INT PRIMARY KEY,
  product_name VARCHAR(100),
  category VARCHAR(50),
  unit_price INT,
  unit_cost INT
) ENGINE=InnoDB;

CREATE TABLE orders (
  order_id INT PRIMARY KEY,
  customer_id INT,
  employee_id INT,
  order_date DATE,
  status VARCHAR(20),
  channel VARCHAR(20),
  CHECK (status IN ('Completed','Cancelled','Returned')),
  CHECK (channel IN ('Online','In-Store','Partner')),
  FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
  FOREIGN KEY (employee_id) REFERENCES employees(employee_id)
) ENGINE=InnoDB;

CREATE TABLE order_items (
  order_item_id INT PRIMARY KEY,
  order_id INT,
  product_id INT,
  quantity INT,
  discount_pct DECIMAL(4,2),
  FOREIGN KEY (order_id) REFERENCES orders(order_id),
  FOREIGN KEY (product_id) REFERENCES products(product_id)
) ENGINE=InnoDB;

CREATE TABLE sales_targets (
  employee_id INT,
  year INT,
  quarter INT,
  target_amount INT,
  PRIMARY KEY (employee_id, year, quarter),
  FOREIGN KEY (employee_id) REFERENCES employees(employee_id)
) ENGINE=InnoDB;

